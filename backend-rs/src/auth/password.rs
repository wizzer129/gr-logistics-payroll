//! Argon2id hashing/verification. Verifies the PHC strings `Bun.password` already wrote to
//! `users.password_hash`. CPU-bound (~tens of ms), so it runs on the blocking pool rather
//! than stalling the async runtime.

use anyhow::anyhow;
use argon2::{
    Algorithm, Argon2, Params, Version,
    password_hash::{PasswordHasher, PasswordVerifier, phc::PasswordHash},
};

/// Same cost as `Bun.password`'s argon2id defaults (m=64 MiB, t=2, p=1), so hashes written
/// by either backend are indistinguishable.
fn hasher() -> Argon2<'static> {
    let params = Params::new(65536, 2, 1, None).expect("static argon2 params are valid");
    Argon2::new(Algorithm::Argon2id, Version::V0x13, params)
}

/// Verified when the email doesn't exist, so a login for an unknown user takes as long as
/// one with a wrong password (no account enumeration by timing).
const DUMMY_HASH: &str = "$argon2id$v=19$m=65536,t=2,p=1$qGwulwFjunboRqjguU6ZO91eDZin/SISpO23hKsKNP4$O8/J8ZsJ7En4WOCEy6+DnUg4dcoysbY/n2UGT2ZSVUA";

pub async fn hash_password(password: String) -> anyhow::Result<String> {
    tokio::task::spawn_blocking(move || {
        let hash: PasswordHash = hasher()
            .hash_password(password.as_bytes())
            .map_err(|e| anyhow!("password hashing failed: {e}"))?;
        Ok(hash.to_string())
    })
    .await?
}

/// `Ok(false)` for a wrong password; `Err` only for a malformed stored hash.
pub async fn verify_password(password: String, hash: String) -> anyhow::Result<bool> {
    tokio::task::spawn_blocking(move || {
        let parsed = PasswordHash::new(&hash)
            .map_err(|e| anyhow!("stored password hash is invalid: {e}"))?;
        // Params come from the parsed hash, not from the Argon2 instance.
        Ok(Argon2::default()
            .verify_password(password.as_bytes(), &parsed)
            .is_ok())
    })
    .await?
}

pub async fn burn_verify_time(password: String) {
    let _ = verify_password(password, DUMMY_HASH.to_owned()).await;
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Generated by `Bun.password.hash('bun-fixture-password', { algorithm: 'argon2id' })`.
    const BUN_HASH: &str = DUMMY_HASH;

    #[tokio::test]
    async fn verifies_a_hash_written_by_bun() {
        assert!(
            verify_password("bun-fixture-password".into(), BUN_HASH.into())
                .await
                .unwrap()
        );
        assert!(
            !verify_password("wrong".into(), BUN_HASH.into())
                .await
                .unwrap()
        );
    }

    #[tokio::test]
    async fn round_trips_with_bun_compatible_params() {
        let hash = hash_password("hunter42".into()).await.unwrap();
        assert!(
            hash.starts_with("$argon2id$v=19$m=65536,t=2,p=1$"),
            "{hash}"
        );
        assert!(verify_password("hunter42".into(), hash).await.unwrap());
    }

    #[tokio::test]
    async fn malformed_hash_is_an_error_not_a_mismatch() {
        assert!(
            verify_password("x".into(), "not-a-hash".into())
                .await
                .is_err()
        );
    }
}
